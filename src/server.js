/**
 * hyper-mock: Core HTTP Server
 */

import { createServer } from 'node:http';
import { ChaosEngine } from './chaos.js';
import { handleSseStream } from './sse.js';

export function createMockServer(config = {}) {
  const chaos = new ChaosEngine({
    latency: config.latency,
    chaosRate: config.chaosRate,
    rateLimit: config.rateLimit,
    rateLimitWindowMs: config.rateLimitWindowMs
  });

  const routes = new Map(); // "METHOD /path" -> handler or response

  // Prepopulate configured routes
  if (config.routes) {
    for (const [key, value] of Object.entries(config.routes)) {
      routes.set(normalizeRouteKey(key), value);
    }
  }

  const server = createServer(async (req, res) => {
    const startTime = Date.now();
    const url = new URL(req.url, `http://${req.headers.host || 'localhost'}`);
    const method = req.method.toUpperCase();
    const routeKey = `${method} ${url.pathname}`;

    // Enable CORS by default
    res.setHeader('Access-Control-Allow-Origin', '*');
    res.setHeader('Access-Control-Allow-Methods', 'GET, POST, PUT, DELETE, PATCH, OPTIONS');
    res.setHeader('Access-Control-Allow-Headers', '*');

    if (method === 'OPTIONS') {
      res.writeHead(204);
      res.end();
      return;
    }

    // 1. Check Rate Limiter
    if (chaos.isRateLimited()) {
      res.writeHead(429, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify({ error: 'Too Many Requests (Chaos Rate Limit)' }));
      logRequest(method, url.pathname, 429, Date.now() - startTime, config.quiet);
      return;
    }

    // 2. Inject Latency Jitter
    await chaos.applyLatency();

    // 3. Inject Chaos Errors
    if (chaos.shouldInjectFailure()) {
      const status = chaos.getRandomChaosStatus();
      res.writeHead(status, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify({ error: `Chaos Injection ${status}`, timestamp: new Date().toISOString() }));
      logRequest(method, url.pathname, status, Date.now() - startTime, config.quiet);
      return;
    }

    // 4. SSE Stream endpoint
    if (url.pathname === '/api/chat/stream' || url.pathname === '/stream') {
      await handleSseStream(res);
      logRequest(method, url.pathname, 200, Date.now() - startTime, config.quiet);
      return;
    }

    // 5. Match explicit route
    if (routes.has(routeKey)) {
      const responseDef = routes.get(routeKey);
      const statusCode = responseDef.status || 200;
      const body = responseDef.body !== undefined ? responseDef.body : responseDef;

      res.writeHead(statusCode, { 'Content-Type': 'application/json' });
      res.end(typeof body === 'string' ? body : JSON.stringify(body));
      logRequest(method, url.pathname, statusCode, Date.now() - startTime, config.quiet);
      return;
    }

    // 6. Default fallback / health check
    if (url.pathname === '/' || url.pathname === '/health') {
      res.writeHead(200, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify({ status: 'ok', server: 'hyper-mock', uptime: process.uptime() }));
      logRequest(method, url.pathname, 200, Date.now() - startTime, config.quiet);
      return;
    }

    // 7. Dynamic JSON echo fallback
    res.writeHead(200, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({
      message: 'Mock response generated by hyper-mock',
      path: url.pathname,
      method,
      query: Object.fromEntries(url.searchParams.entries())
    }));
    logRequest(method, url.pathname, 200, Date.now() - startTime, config.quiet);
  });

  return server;
}

function normalizeRouteKey(key) {
  const parts = key.trim().split(/\s+/);
  if (parts.length === 1) return `GET ${parts[0]}`;
  return `${parts[0].toUpperCase()} ${parts[1]}`;
}

function logRequest(method, path, status, durationMs, quiet) {
  if (quiet) return;
  const color = status >= 500 ? '\x1b[31m' : status >= 400 ? '\x1b[33m' : '\x1b[32m';
  console.log(`[hyper-mock] ${method.padEnd(6)} ${path} -> ${color}${status}\x1b[0m (${durationMs}ms)`);
}

